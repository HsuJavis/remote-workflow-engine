import { writeFileSync } from 'node:fs';
const list = await (await fetch('http://127.0.0.1:9229/json/list')).json();
const ws = new WebSocket(list[0].webSocketDebuggerUrl);
let id = 0; const pend = new Map();
ws.onmessage = (m) => { const d = JSON.parse(m.data); if (d.id && pend.has(d.id)) { pend.get(d.id)(d); pend.delete(d.id); } };
await new Promise((r) => (ws.onopen = r));
const send = (method, params = {}) => new Promise((r) => { const i = ++id; pend.set(i, r); ws.send(JSON.stringify({ id: i, method, params })); });
await send('Profiler.enable'); await send('Profiler.setSamplingInterval', { interval: 1000 }); await send('Profiler.start');
console.error('profiling'); await new Promise((r) => setTimeout(r, Number(process.argv[2]) * 1000));
const p = await send('Profiler.stop'); writeFileSync(process.argv[3], JSON.stringify(p.result.profile)); console.error('saved'); ws.close();
